const fs = require('fs');
const path = require('path');

/**
 * Vendor the single onnxruntime-web wasm binary the annotation box-decoder needs
 * into public/onnx/ so CRA serves it as a static asset and ort can fetch it from
 * `${PUBLIC_URL}/onnx/` at runtime.
 *
 * We copy ONLY `ort-wasm-simd-threaded.wasm` (~11 MB). The box decoder runs the
 * default 'wasm' execution provider single-threaded (numThreads=1, no COOP/COEP
 * headers exist, so multi-threading is unavailable anyway). We deliberately skip:
 *   - ort-wasm-simd-threaded.jsep.wasm  (21 MB WebGPU/JSEP build, unused)
 *   - ort-training-wasm-simd-threaded.wasm (11 MB training build, unused)
 * so the vendored payload stays minimal.
 *
 * The vendored file is gitignored and regenerated by this script on postinstall
 * and prebuild, so it is never committed.
 */

const WASM_FILE = 'ort-wasm-simd-threaded.wasm';

const srcFile = path.join(
  __dirname,
  '..',
  'node_modules',
  'onnxruntime-web',
  'dist',
  WASM_FILE,
);
const destDir = path.join(__dirname, '..', 'public', 'onnx');
const destFile = path.join(destDir, WASM_FILE);

try {
  if (!fs.existsSync(srcFile)) {
    // onnxruntime-web not installed yet (e.g. CI cache miss). Warn but do not
    // fail the whole install/build: the box tool is optional and its absence is
    // handled gracefully at runtime.
    console.warn('⚠️  onnxruntime-web wasm not found at', srcFile, '- skipping ort wasm copy');
    process.exit(0);
  }

  if (!fs.existsSync(destDir)) {
    fs.mkdirSync(destDir, { recursive: true });
  }

  fs.copyFileSync(srcFile, destFile);
  console.log('✅ Copied', WASM_FILE, 'to public/onnx/');
} catch (error) {
  console.error('❌ Error copying ort wasm:', error.message);
  process.exit(1);
}
