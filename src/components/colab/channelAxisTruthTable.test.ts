import { axisRoles, ngffChannelAxis, NgffAxis } from './ngffLayout';
import table from './channelAxisTruthTable.json';

/**
 * The browser reproduces the SERVICE's answer, case by case.
 *
 * A review found why a hand-written expectation of the service is not enough:
 * it is exactly how this browser can agree with somebody's READING of the
 * service rather than with the service. My first version of this rule compared
 * the raw type string, because I had checked it against the service's resolver
 * alone and not against the parse step that lowercases every type first. On a
 * store typed `"Channel"` the service found the channel axis and the browser
 * did not, so the trainer would have read those channels while the viewer
 * pinned the axis and drew single-channel planes.
 *
 * So the expectation is not written here. `channelAxisTruthTable.json` is
 * GENERATED by running the service's own `parse_ngff_multiscales` and
 * `ngff_axis_roles` over these axis lists, and it records the ref it came
 * from. Regenerate it when the service's rule moves:
 *
 *   git -C <service repo> show <ref>:apps/annotation-broker/broker_core.py \
 *     > /tmp/brokerprobe/broker_core.py
 *   python3 gen-channel-axis-table.py <ref> > channelAxisTruthTable.json
 *
 * WHAT THIS STILL CANNOT DO, said rather than left to be discovered: it pins
 * the browser to a SNAPSHOT of the service. A change on that side moves the
 * two apart until the table is regenerated, and nothing here will notice.
 * That is the residual risk of two implementations of one rule, and the only
 * thing that removes it is the browser consuming the roles the service already
 * computed, which the issue records as the open question it is.
 */

interface TruthCase {
  label: string;
  axes: Array<{ name: string; type?: unknown }>;
  roles?: { y: number; x: number; c: number | null };
  raises?: string;
}

const CASES = (table as { generated_from: string; cases: TruthCase[] }).cases;

describe(`the channel axis, against the service at ${(table as any).generated_from}`, () => {
  it('has a table with the cases that discriminate', () => {
    // A table that lost its interesting rows would make every case below
    // pass vacuously, so the rows this rule turns on are named here.
    const labels = CASES.map((c) => c.label);
    expect(labels).toEqual(
      expect.arrayContaining([
        'TRAP: spatial c beside channel ch',
        'capitalised Channel',
        'all spatial, one named c',
        'partially typed, untyped c',
        'non-string type counts as declared',
        'two channel-typed axes',
      ]),
    );
    expect(CASES.length).toBeGreaterThanOrEqual(12);
  });

  CASES.forEach((testCase) => {
    it(`matches the service on: ${testCase.label}`, () => {
      const axes = testCase.axes as NgffAxis[];
      if (testCase.raises) {
        // The service refuses; so must this, rather than guessing a first.
        expect(() => ngffChannelAxis(axes)).toThrow();
        expect(() => axisRoles(axes, axes.length)).toThrow();
        return;
      }
      const expected = testCase.roles!;
      // `ngff_channel_axis` answers -1 for "none"; `axisRoles` carries that
      // through as null, which is the shape the service's roles dict uses.
      const resolved = ngffChannelAxis(axes);
      expect(resolved === -1 ? null : resolved).toEqual(expected.c);

      const roles = axisRoles(axes, axes.length);
      expect({ y: roles.y, x: roles.x, c: roles.c }).toEqual(expected);
    });
  });
});
